export function isLoggedIn(): boolean {
  try {
    return localStorage.getItem("logged_in") === "1";
  } catch {
    return false;
  }
}

export async function logout(): Promise<void> {
  await fetch(`${API_BASE}/auth/logout`, {
    method: "POST",
    headers: { "Content-Type": "application/json", ...CSRF_HEADERS },
    credentials: "include",
  }).catch(() => undefined);
  setLoggedInFlag(false);
}

export async function streamChatMessage(
  courseSlug: string | null,
  chapterId: number | null,
  message: string,
  onEvent: (event: ChatStreamEvent) => void,
  signal?: AbortSignal,
): Promise<void> {
  async function attempt(): Promise<Response> {
    return fetch(`${API_BASE}/me/chat/stream`, {
      method: "POST",
      headers: { "Content-Type": "application/json", ...CSRF_HEADERS },
      credentials: "include",
      body: JSON.stringify({ course_slug: courseSlug, chapter_id: chapterId, message }),
      signal,
    });
  }

  let resp = await attempt();
  if (resp.status === 401) {
    if (await refreshAccessToken()) {
      resp = await attempt();
    }
  }
  if (!resp.ok || !resp.body) throw new Error(`${resp.status}: ${await resp.text()}`);

  const reader = resp.body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    const lines = buffer.split("\n");
    buffer = lines.pop() ?? "";
    for (const line of lines) {
      if (line.trim()) onEvent(JSON.parse(line) as ChatStreamEvent);
    }
  }
  if (buffer.trim()) onEvent(JSON.parse(buffer) as ChatStreamEvent);
}

export async function streamChapterContent(
  courseSlug: string,
  chapterId: number,
  onEvent: (event: ChapterContentEvent) => void,
  signal?: AbortSignal,
): Promise<void> {
  async function attempt(): Promise<Response> {
    return fetch(`${API_BASE}/courses/${courseSlug}/chapters/${chapterId}/content`, {
      headers: CSRF_HEADERS,
      credentials: "include",
      signal,
    });
  }

  let resp = await attempt();
  if (resp.status === 401) {
    // The access-token cookie expired — refresh once and retry, mirroring
    // `request`.
    if (await refreshAccessToken()) {
      resp = await attempt();
    }
  }
  if (!resp.ok || !resp.body) throw new Error(`${resp.status}: ${await resp.text()}`);

  const reader = resp.body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    const lines = buffer.split("\n");
    buffer = lines.pop() ?? "";
    for (const line of lines) {
      if (line.trim()) onEvent(JSON.parse(line) as ChapterContentEvent);
    }
  }
  if (buffer.trim()) onEvent(JSON.parse(buffer) as ChapterContentEvent);
}

export interface ExportApiError {
  status: number;
  code?: string;
  message: string;
}

export function parseExportApiError(error: unknown): ExportApiError {
  const fallback: ExportApiError = { status: 0, message: "Request failed. Please try again." };
  if (!(error instanceof Error)) return fallback;
  const separator = error.message.indexOf(": ");
  if (separator < 0) return { ...fallback, message: error.message || fallback.message };
  const status = Number(error.message.slice(0, separator));
  const raw = error.message.slice(separator + 2);
  if (!Number.isInteger(status)) return { ...fallback, message: error.message };
  try {
    const parsed = JSON.parse(raw) as { detail?: unknown };
    if (typeof parsed.detail === "string") return { status, message: parsed.detail };
    if (parsed.detail && typeof parsed.detail === "object") {
      const detail = parsed.detail as { code?: unknown; message?: unknown };
      return {
        status,
        code: typeof detail.code === "string" ? detail.code : undefined,
        message: typeof detail.message === "string" ? detail.message : raw,
      };
    }
  } catch {
    // Fall through to the raw response text below.
  }
  return { status, message: raw || fallback.message };
}
